public class Ejercicio4 {
    public static void main(String[] args) {
        for (int i = 1; i <= 20; i++) {
            System.out.print(i + " ");
        }
        System.out.println(); 
        int j = 20;
        while (j >= 1) {
            System.out.print(j + " ");
            j--;
        }
        System.out.println();

    }
}
